'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8');
const home = read('public/index.html');
const aruvix = read('public/aruvix.html');
const baseCss = read('public/site-redesign.css');
const polish = read('public/site-polish.css');
const common = read('public/site-polish.js');
const homeScript = read('public/site-redesign.js');
const backend = read('app.js');
const count = (input, regex) => (input.match(regex) || []).length;
const check = (name, valid) => { assert.ok(valid, name); process.stdout.write('PASS ' + name + '\n'); };
check('Legacy homepage CSS excluded to avoid grid and section collisions', !home.includes('href="/styles.css') && backend.includes('href="/styles.css?v=4"'));
check('Full-bleed section layout no longer inherits legacy sizing', baseCss.includes('body{margin:0') && baseCss.includes('.experience-layout{display:grid;'));
check('Experience heading is sticky only on desktop', baseCss.includes('.experience-heading{position:sticky') && baseCss.includes('.experience-heading{position:static'));
check('Single homepage main landmark', count(home, /<main\s/gi) === 1);
check('Single back-to-top control', count(home, /id="back-to-top"/g) === 1);
check('Consistent theme control on homepage and Aruvix', home.includes('id="studio-theme-toggle"') && aruvix.includes('id="studio-theme-toggle"'));
check('Shared stylesheet on all page types', home.includes('/site-polish.css') && aruvix.includes('/site-polish.css'));
check('Shared theme persistence and aria state', common.includes('portfolio-theme') && common.includes('aria-pressed'));
check('Resume PDF path exists', fs.existsSync(path.join(root, 'public/resume/pdf/Amrishkhan-Sheik-Abdullah-Resume.pdf')));
check('Resume DOCX path exists', fs.existsSync(path.join(root, 'public/resume/doc/Amrishkhan-Sheik-Abdullah-Resume.docx')));
check('Resume links in the UI', home.includes('/resume/pdf/Amrishkhan-Sheik-Abdullah-Resume.pdf') && home.includes('/resume/doc/Amrishkhan-Sheik-Abdullah-Resume.docx'));
check('Homepage section navigation and writing feed', home.includes('id="writing"') && home.includes('id="work"') && homeScript.includes('/api/blogs'));
check('Blog article reader and canonical metadata', home.includes('id="blog-detail"') && home.includes('rel="canonical"'));
check('Blog and Aruvix Express routes preserved', backend.includes('app.get("/blog/:slug"') && backend.includes('app.get("/aruvix"'));
check('DEV.to article payload sanitized', backend.includes('bodyHtml: sanitizeDevArticleHtml(article.bodyHtml)'));
check('Article theme supports dark mode and SSR fallback', polish.includes('html.is-blog-route[data-theme="dark"]') && polish.includes('html.is-blog-route #blog-detail[hidden]'));
check('Reduced-motion styles present', baseCss.includes('prefers-reduced-motion'));
check('Accessible mobile navigation controls', home.includes('aria-controls="primary-nav"') && aruvix.includes('aria-controls="primary-nav"'));
console.log('Portfolio quality checks passed.');
